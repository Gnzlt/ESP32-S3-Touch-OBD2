"""
Builds the boot splash (also the parked screen's backdrop) from a picture of
the bike drawn for a black background: a line drawing such as
tools/art/bike.png, or an illustration. It is used as drawn: crop to the bike,
fit it inside the 360x360 round panel, crush near-black noise (JPEG) to true
black, and write an LVGL 9 RGB565 image as C source.

    python tools/make_splash.py [<picture>]        # default: tools/art/bike.png

Writes main/ui/assets/splash_bike.c and tools/splash_preview.png. Needs Pillow.
The bike profile's BIKE_NAME is drawn under it by the firmware.
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter

SIZE = 360
CENTER_Y = 150          # the bike sits a little above the middle; the name goes below
MAX_RADIUS = 162        # no bike pixel beyond this from the panel centre
MAX_WIDTH = 256         # bike width cap: smaller than the circle allows, leaving black around it
CONTENT = 28            # brightest channel above this counts as bike (for crop and fit)
BLACK_LO, BLACK_HI = 8, 20   # below LO is background noise -> 0; ramps back to full by HI
ROOT = Path(__file__).resolve().parent.parent


def crop(src: Image.Image) -> Image.Image:
    # Brightest channel per pixel; a small open drops isolated JPEG speckles.
    lum = ImageChops.lighter(ImageChops.lighter(*src.split()[:2]), src.split()[2])
    mask = lum.point(lambda v: 255 if v > CONTENT else 0).filter(ImageFilter.MinFilter(5)).filter(ImageFilter.MaxFilter(5))
    left, top, right, bottom = mask.getbbox()
    pad = 12   # keep the soft outer halo
    return src.crop((max(0, left - pad), max(0, top - pad), min(src.width, right + pad), min(src.height, bottom + pad)))


def fit(bike: Image.Image) -> tuple[Image.Image, int, int]:
    """The largest size whose visible pixels all stay inside MAX_RADIUS."""
    width = MAX_WIDTH
    while True:
        h = round(bike.height * width / bike.width)
        img = bike.resize((width, h), Image.LANCZOS)
        x, y = (SIZE - width) // 2, CENTER_Y - h // 2
        px = img.load()
        ok = all(
            max(px[i, j]) <= CONTENT or math.hypot(x + i - SIZE / 2, y + j - SIZE / 2) <= MAX_RADIUS
            for j in range(0, h, 2) for i in range(0, width, 2)
        )
        if ok:
            return img, x, y
        width -= 4


def crush_blacks(img: Image.Image) -> Image.Image:
    """True black where the JPEG left noise, so RGB565 shows no blotches; a ramp keeps edges soft."""
    out = img.copy()
    px = out.load()
    for j in range(out.height):
        for i in range(out.width):
            r, g, b = px[i, j]
            m = max(r, g, b)
            if m < BLACK_HI:
                k = max(0.0, (m - BLACK_LO) / (BLACK_HI - BLACK_LO))
                px[i, j] = (round(r * k), round(g * k), round(b * k))
    return out


def main() -> None:
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    src = Image.open(sys.argv[1] if len(sys.argv) == 2 else ROOT / "tools" / "art" / "bike.png").convert("RGB")
    bike, x, y = fit(crop(src))

    out = Image.new("RGB", (SIZE, SIZE))
    out.paste(crush_blacks(bike), (x, y))

    # Black outside the panel circle (the corners are never shown anyway).
    mask = Image.new("L", (SIZE, SIZE), 0)
    m = mask.load()
    for j in range(SIZE):
        for i in range(SIZE):
            m[i, j] = 255 if math.hypot(i + 0.5 - SIZE / 2, j + 0.5 - SIZE / 2) <= SIZE / 2 else 0
    out = Image.composite(out, Image.new("RGB", (SIZE, SIZE)), mask)

    out.save(ROOT / "tools" / "splash_preview.png")
    write_c(out, ROOT / "main" / "ui" / "assets" / "splash_bike.c")
    print(f"bike {bike.width}x{bike.height} at ({x},{y}); wrote splash_bike.c and splash_preview.png")


def write_c(img: Image.Image, path: Path) -> None:
    data = bytearray()
    for r, g, b in img.convert("RGB").get_flattened_data():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))   # little endian, LVGL's native RGB565
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    path.write_text(
        "/* Generated by tools/make_splash.py. Do not edit. */\n"
        '#include "lvgl.h"\n\n'
        "static const LV_ATTRIBUTE_LARGE_CONST uint8_t splash_bike_map[] = {\n    "
        + ",\n    ".join(lines)
        + "\n};\n\n"
        "const lv_image_dsc_t splash_bike = {\n"
        "    .header = {\n"
        "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        "        .cf = LV_COLOR_FORMAT_RGB565,\n"
        f"        .w = {SIZE},\n"
        f"        .h = {SIZE},\n"
        f"        .stride = {SIZE * 2},\n"
        "    },\n"
        "    .data_size = sizeof(splash_bike_map),\n"
        "    .data = splash_bike_map,\n"
        "};\n"
    )


if __name__ == "__main__":
    main()
