"""
Builds the Tyres page's bike from a line drawing (white lines on black, bike
facing right, rear wheel on the left). The page puts a ring over each tyre
with its pressure inside, so the tyres themselves are the gauges.

Thin strokes scaled down to the page would fade to nothing, so they are
thickened first, then scaled with smoothing and brightened back to full lines.

    python tools/make_tyre_bike.py [<drawing.png> [--rear X,Y,R --front X,Y,R]]

The defaults are tools/art/bike.png (from tools/make_bike_art.py) and its tyre
positions. For your own drawing, give each tyre's centre and outer radius in
the drawing's pixels. Writes main/ui/assets/tyre_bike.c (LVGL 9 RGB565),
main/ui/assets/tyre_bike.h (size, tyre centres and radii) and
tools/tyre_bike_preview.png. Needs Pillow and numpy.
"""
import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent

# tools/art/bike.png: each tyre's centre and outer radius.
DRAWING = ROOT / "tools" / "art" / "bike.png"
REAR = (520, 1150, 300)
FRONT = (1880, 1150, 300)
FRONT_R_PAGE = 36         # the front tyre's radius on the page, px (the rings still fit "2.25" inside)
THICKEN = 5               # MaxFilter size at full size: a ~9 px stroke becomes ~13, about 1.6 px on the page
GAIN = 1.7                # brightens the smoothed lines back up
LINE = (214, 219, 226)    # the lines' colour at full strength


def xyr(text):
    x, y, r = (int(v) for v in text.split(","))
    return x, y, r


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("drawing", nargs="?", default=DRAWING)
    ap.add_argument("--rear", type=xyr, default=REAR, help="rear tyre centre and outer radius, X,Y,R")
    ap.add_argument("--front", type=xyr, default=FRONT, help="front tyre centre and outer radius, X,Y,R")
    args = ap.parse_args()
    REAR_, FRONT_ = args.rear, args.front
    src = Image.open(args.drawing).convert("L")
    a = np.asarray(src)
    ys, xs = np.nonzero(a > 128)
    pad = 12
    box = (xs.min() - pad, ys.min() - pad, xs.max() + pad, ys.max() + pad)
    s = FRONT_R_PAGE / FRONT_[2]
    w, h = round((box[2] - box[0]) * s), round((box[3] - box[1]) * s)
    lines = src.crop(box).filter(ImageFilter.MaxFilter(THICKEN)).resize((w, h), Image.LANCZOS)
    k = np.clip(np.asarray(lines).astype(np.float32) / 255.0 * GAIN, 0.0, 1.0)
    rgb = (k[..., None] * np.array(LINE, np.float32)).round().astype(np.uint8)
    img = Image.fromarray(rgb, "RGB")

    def page_xy(c):
        return round((c[0] - box[0]) * s), round((c[1] - box[1]) * s), round(c[2] * s)

    rear, front = page_xy(REAR_), page_xy(FRONT_)
    write_c(img, ROOT / "main" / "ui" / "assets" / "tyre_bike.c")
    (ROOT / "main" / "ui" / "assets" / "tyre_bike.h").write_text(
        "/* Generated by tools/make_tyre_bike.py. Do not edit. */\n"
        "#pragma once\n\n"
        '#include "lvgl.h"\n\n'
        "LV_IMAGE_DECLARE(tyre_bike);\n\n"
        "// The image's size, and each tyre's centre and outer radius in it, px.\n"
        f"#define TYRE_BIKE_W       {w}\n"
        f"#define TYRE_BIKE_H       {h}\n"
        f"#define TYRE_BIKE_REAR_X  {rear[0]}\n"
        f"#define TYRE_BIKE_REAR_Y  {rear[1]}\n"
        f"#define TYRE_BIKE_REAR_R  {rear[2]}\n"
        f"#define TYRE_BIKE_FRONT_X {front[0]}\n"
        f"#define TYRE_BIKE_FRONT_Y {front[1]}\n"
        f"#define TYRE_BIKE_FRONT_R {front[2]}\n"
    )
    img.save(ROOT / "tools" / "tyre_bike_preview.png")
    print(f"tyre bike {w}x{h}; rear tyre {rear}, front tyre {front}")


def write_c(img, path):
    data = bytearray()
    for r, g, b in img.convert("RGB").get_flattened_data():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))   # little endian, LVGL's native RGB565
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    path.write_text(
        "/* Generated by tools/make_tyre_bike.py. Do not edit. */\n"
        '#include "lvgl.h"\n\n'
        "static const LV_ATTRIBUTE_LARGE_CONST uint8_t tyre_bike_map[] = {\n    "
        + ",\n    ".join(lines)
        + "\n};\n\n"
        "const lv_image_dsc_t tyre_bike = {\n"
        "    .header = {\n"
        "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        "        .cf = LV_COLOR_FORMAT_RGB565,\n"
        f"        .w = {img.width},\n"
        f"        .h = {img.height},\n"
        f"        .stride = {img.width * 2},\n"
        "    },\n"
        "    .data_size = sizeof(tyre_bike_map),\n"
        "    .data = tyre_bike_map,\n"
        "};\n"
    )


if __name__ == "__main__":
    main()
